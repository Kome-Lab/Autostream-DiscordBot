func TestMSRManagedAutoStartSendsOriginalObservationOnce(t *testing.T) {
	var calls atomic.Int32
	var inspections atomic.Int32
	var inspectionMode atomic.Int32
	want := AutoStartRequest{RequestID: "original-attempt", ExpectedHoldRevision: 9,
		ExpectedStreamRevision: "stream-r", ExpectedSettingsRevision: "settings-r", ExpectedRunID: ""}
	panel := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method == http.MethodGet {
			inspections.Add(1)
			if r.URL.Path != "/services/streams/stream/auto-start/attempts/original-attempt" || r.Header.Get("Authorization") != "Bearer synthetic-test-only" || r.ContentLength > 0 {
				t.Error("Inspect changed the original attempt or used a mutation body")
			}
			requestID := "original-attempt"
			if inspectionMode.Load() == 1 {
				requestID = "different-attempt"
			}
			resource := lifecycle.ResourceRef{Kind: lifecycle.Stream, OwnerID: "encoder-test", ResourceID: "stream"}
			observation := lifecycle.BoundaryObservation{Address: lifecycle.BoundaryAddress{Kind: lifecycle.BackendMutation, OwnerID: "encoder-test", Resource: resource, SubBoundary: lifecycle.ServiceApply}, Knowledge: lifecycle.KnowledgeUnknown, Presence: lifecycle.NotObserved,
				Outcome: lifecycle.Fact[lifecycle.Outcome]{State: lifecycle.Unavailable, Unavailable: &lifecycle.UnavailableReason{Code: "ACK_NOT_OBSERVED"}}}
			if inspectionMode.Load() == 2 {
				observation.Presence = lifecycle.Present
			}
			_ = json.NewEncoder(w).Encode(map[string]any{"admission": map[string]any{"request_id": requestID, "stream_id": "stream", "records": []lifecycle.Record{msrInspectionRecord()}}, "start_observations": []lifecycle.BoundaryObservation{observation}, "gate": lifecycle.NotQualified})
			return
		}
		calls.Add(1)
		if r.Method != http.MethodPost || r.URL.Path != "/services/streams/stream/start" {
			t.Error("managed request used wrong product path")
		}
		var raw map[string]json.RawMessage
		if err := json.NewDecoder(r.Body).Decode(&raw); err != nil {
			t.Error(err)
		}
		if len(raw) != 5 || string(raw["expected_run_id"]) != `""` {
			t.Error("explicit absent Run or immutable fields were replaced/defaulted")
		}
		data, _ := json.Marshal(raw)
		var got AutoStartRequest
		if err := json.Unmarshal(data, &got); err != nil || got != want {
			t.Error("original request observation changed")
		}
		w.WriteHeader(http.StatusServiceUnavailable)
	}))
	defer panel.Close()
	client := Client{Config: Config{ControlPanelURL: panel.URL, Token: "synthetic-test-only", ServiceID: "bot", ServiceName: "bot", ServicePublicURL: "https://bot.example.invalid"}}
	requestErr := client.StartManagedStream(t.Context(), "stream", want)
	if requestErr == nil {
		t.Fatal("unknown response was promoted to success")
	}
	if calls.Load() != 1 {
		t.Fatalf("managed client calls=%d error=%v", calls.Load(), requestErr)
	}
	inspection, inspectErr := client.InspectManagedStream(t.Context(), "stream", want.RequestID)
	if inspectErr != nil || inspection.Admission.RequestID != want.RequestID || inspection.Gate != lifecycle.NotQualified || len(inspection.StartObservations) != 1 || inspection.StartObservations[0].Knowledge != lifecycle.KnowledgeUnknown {
		t.Fatalf("pure original-attempt inspection was lost or promoted: %v %+v", inspectErr, inspection)
	}
	for _, mode := range []int32{1, 2} {
		inspectionMode.Store(mode)
		if _, err := client.InspectManagedStream(t.Context(), "stream", want.RequestID); err == nil {
			t.Fatal("mismatched correlation or invalid UNKNOWN union was accepted")
		}
	}
	if calls.Load() != 1 || inspections.Load() != 3 {
		t.Fatal("Inspect issued a second Start or retried its result query")
	}
	if _, err := client.InspectManagedStream(t.Context(), "stream", "invalid/request"); err == nil || inspections.Load() != 3 {
		t.Fatal("invalid original request identifier entered result lookup")
	}
	want.ExpectedHoldRevision = 0
	if err := client.StartManagedStream(t.Context(), "stream", want); err == nil || calls.Load() != 1 {
		t.Fatal("missing original revision was sent as a default/current value")
	}
}

// The fixture is independently specified product metadata; no expected result
// is generated by the consumer validator under test.
func msrInspectionRecord() lifecycle.Record {
	resource := lifecycle.ResourceRef{Kind: lifecycle.Stream, OwnerID: "encoder-test", ResourceID: "stream"}
	ref := lifecycle.ContractRef{ContractID: lifecycle.CC02, LogicalRevision: 1, SpecRef: lifecycle.SpecRef, ModuleCommitRef: "d32ea3514b1c1010391caae0348b0ff9e751f447"}
	record := lifecycle.Record{Header: lifecycle.Header{ContractRef: ref, RecordKey: lifecycle.RecordKey{ContractRef: ref, OwnerID: "cp-test", RecordID: "original-attempt"},
		Correlation: lifecycle.Correlation{RequestID: "original-attempt", OperationID: "auto-start", AttemptID: "original-attempt", StepID: "start", ExecutionKey: "original-attempt"},
		DomainRef:   lifecycle.DomainRef{DeploymentID: "synthetic-deployment", Realm: "synthetic-realm", DomainID: "synthetic-domain", MembershipRevision: 1, SnapshotRef: "membership-test", Resources: []lifecycle.ResourceRef{resource}},
		ProducerRef: lifecycle.ProducerRef{ComponentID: "C01", ServiceID: "cp-test", HostID: "synthetic-cp", BootID: "cp-boot", ProcessIncarnation: "cp-process", WriterID: "test-only"}, RecordRevision: 9,
		ProfileRef: lifecycle.ProfileRef{ProfileID: lifecycle.ExplicitResume, Revision: 1}}, Vector: &lifecycle.VectorRecord{}}
	for _, axis := range []lifecycle.Axis{lifecycle.Membership, lifecycle.Admission, lifecycle.Ownership, lifecycle.Fence, lifecycle.Boot, lifecycle.Process, lifecycle.RunAxis, lifecycle.ConfigAxis} {
		literal := lifecycle.ID("observed-" + string(axis))
		value := lifecycle.VersionedValue{Kind: lifecycle.PresentLiteral, Literal: &literal}
		if axis == lifecycle.Membership {
			v := uint64(1)
			value = lifecycle.VersionedValue{Kind: lifecycle.PresentUint64, Uint64: &v}
		}
		record.Vector.Vector = append(record.Vector.Vector, lifecycle.RevisionEntry{Key: lifecycle.AxisKey{Axis: axis, OwnerID: resource.OwnerID, Resource: resource}, Incarnation: "synthetic-owner", Value: value, SourceFrameRef: "synthetic-cp-frame"})
	}
	return record
}
